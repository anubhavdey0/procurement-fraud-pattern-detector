"""A made-up market with a planted cartel.

Used by the tests and by ``bidscreen demo``, so the whole pipeline can be run
and checked without downloading anything. Every firm, buyer and tender here is
invented.

The competitive part of the market: each buyer has a pool of local firms. A
tender draws a few of them, each bids its own cost plus a margin, and the
lowest bid wins.

The planted cartel: a handful of firms working for one buyer. On their tenders
only cartel members bid. They take turns as the designated winner, the winner
bids just under the estimate, and the others file cover bids packed closely
above it. One member only ever files cover bids. That gives each screen
something to find: a closed group, rotation, a persistent loser, awards near
the estimate, and a tight spread of bids with a gap below it.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from bidscreen.model import Market


def make_market(
    n_buyers: int = 5,
    firms_per_buyer: int = 14,
    tenders_per_buyer: int = 120,
    cartel_size: int = 4,
    cartel_tenders: int = 48,
    with_prices: bool = True,
    seed: int = 0,
) -> Market:
    """Build the synthetic market.

    With ``with_prices=False`` the losing bid amounts are blanked, which
    mimics a source that publishes only who bid and the award value.
    """
    if cartel_size < 3:
        raise ValueError("the cartel needs at least three members")
    rng = np.random.default_rng(seed)
    start = np.datetime64("2022-04-01T10:00")

    tenders: list[dict] = []
    bids: list[dict] = []
    tender_no = 0

    def add_tender(buyer: str, day: int, estimate: float, offers: dict[str, float], collusive):
        nonlocal tender_no
        tender_no += 1
        tender_id = f"SYN-{tender_no:05d}"
        winner = min(offers, key=offers.get)
        date = (
            start + np.timedelta64(int(day), "D") + np.timedelta64(int(rng.integers(0, 360)), "m")
        )
        tenders.append(
            {
                "tender_id": tender_id,
                "segment": buyer,
                "buyer": buyer,
                "date": pd.Timestamp(date),
                "estimate": round(estimate, 2),
                "award_value": round(offers[winner], 2),
                "collusive": collusive,
            }
        )
        for firm, value in offers.items():
            bids.append(
                {
                    "tender_id": tender_id,
                    "firm": firm,
                    "bid_value": round(value, 2),
                    "won": firm == winner,
                }
            )

    for b in range(n_buyers):
        buyer = f"Buyer {chr(ord('A') + b)}"
        pool = [f"{buyer} firm {i + 1:02d}" for i in range(firms_per_buyer)]
        # Firms differ in cost, so some win more often than others.
        efficiency = dict(zip(pool, rng.normal(0.0, 0.03, len(pool)), strict=True))
        for day in np.sort(rng.integers(0, 540, tenders_per_buyer)):
            estimate = float(rng.lognormal(mean=15.0, sigma=0.6))
            n_bidders = int(rng.integers(2, 7))
            bidders = rng.choice(pool, size=n_bidders, replace=False)
            offers = {
                firm: estimate * (0.88 + efficiency[firm] + rng.normal(0.0, 0.045))
                for firm in bidders
            }
            add_tender(buyer, day, estimate, offers, False)

    # The cartel works for the first buyer and bids on nothing else.
    cartel_buyer = "Buyer A"
    cartel = [f"Cartel firm {i + 1}" for i in range(cartel_size)]
    takers = cartel[:-1]  # the last member only files cover bids
    for k, day in enumerate(np.sort(rng.integers(0, 540, cartel_tenders))):
        estimate = float(rng.lognormal(mean=15.0, sigma=0.6))
        designated = takers[k % len(takers)]
        others = [f for f in cartel if f != designated]
        covers = rng.choice(others, size=int(rng.integers(2, len(others) + 1)), replace=False)
        winning_bid = estimate * rng.uniform(0.985, 0.999)
        offers = {designated: winning_bid}
        for firm in covers:
            offers[firm] = winning_bid * (1.045 + rng.uniform(0.0, 0.012))
        add_tender(cartel_buyer, day, estimate, offers, True)

    tender_frame = pd.DataFrame(tenders)
    tender_frame["order"] = (tender_frame["date"] - pd.Timestamp(0)) / pd.Timedelta(seconds=1)
    bid_frame = pd.DataFrame(bids)
    bid_frame["cartel_member"] = bid_frame["firm"].isin(cartel)
    bid_frame["cartel"] = np.where(bid_frame["cartel_member"], "planted", None)
    if not with_prices:
        bid_frame["bid_value"] = np.nan

    return Market(
        name="synthetic",
        title="Synthetic demo market",
        tenders=tender_frame,
        bids=bid_frame,
        description="Synthetic market with one planted cartel. All names are invented.",
        source="generated by bidscreen.synthetic",
        currency="INR",
        lowest_bid_wins=True,
        notes=["synthetic data: every firm, buyer and tender is invented"],
    )
